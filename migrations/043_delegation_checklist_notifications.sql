-- 043: notifications for Delegation and Checklist.
--   dim_att_employee.phone_number  - the employee's WhatsApp number (Setup > Dropdown values > Attendance employees); the people who work
--       through Delegation / Checklist are members, and every member is an attendance employee, so this is where their number lives.
--   whatsapp_alert                 - four new alerts (task given, task done, checklist given, checklist item marked). They go to PEOPLE, not a
--       group, so besides the on/off switch and the wording each one says who it reaches: the person it concerns, the EA (an employee chosen
--       here) and the admin (the admins' web screens, plus any admin WhatsApp numbers listed here).
--   app_notification               - the in-app (web) notifications: one row per person per event, shown on the Delegation screen's bell.
--   notify_log                     - every WhatsApp / in-app attempt (who, which alert, sent or why not), for troubleshooting.
-- Safe to run twice.

ALTER TABLE dim_att_employee ADD COLUMN IF NOT EXISTS phone_number varchar(20);

ALTER TABLE whatsapp_alert ADD COLUMN IF NOT EXISTS to_assignee     boolean NOT NULL DEFAULT true;
ALTER TABLE whatsapp_alert ADD COLUMN IF NOT EXISTS to_ea           boolean NOT NULL DEFAULT true;
ALTER TABLE whatsapp_alert ADD COLUMN IF NOT EXISTS to_admin        boolean NOT NULL DEFAULT true;
ALTER TABLE whatsapp_alert ADD COLUMN IF NOT EXISTS ea_employee_key integer REFERENCES dim_att_employee (employee_key) ON DELETE SET NULL;
ALTER TABLE whatsapp_alert ADD COLUMN IF NOT EXISTS admin_numbers   varchar(200);

CREATE TABLE IF NOT EXISTS app_notification (
    notification_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_key         integer NOT NULL REFERENCES dim_user (user_key) ON DELETE CASCADE,
    module           varchar(30) NOT NULL,
    title            varchar(200) NOT NULL,
    body             text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    read_at          timestamptz
);
CREATE INDEX IF NOT EXISTS idx_app_notification_user ON app_notification (user_key, created_at DESC);

CREATE TABLE IF NOT EXISTS notify_log (
    log_key    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at         timestamptz NOT NULL DEFAULT now(),
    alert_key  varchar(40) NOT NULL,
    channel    varchar(10) NOT NULL CHECK (channel IN ('whatsapp', 'app')),
    recipient  varchar(150),
    ok         boolean NOT NULL,
    detail     varchar(500)
);

