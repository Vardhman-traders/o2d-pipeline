CREATE TABLE dim_att_location (
    location_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_name varchar(50) NOT NULL,
    latitude      numeric(10, 7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude     numeric(10, 7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    radius_m      integer NOT NULL DEFAULT 40 CHECK (radius_m BETWEEN 5 AND 5000),   -- how close counts as "at work"
    icon          varchar(8) NOT NULL DEFAULT '📍',
    sort_order    integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_att_location_name ON dim_att_location (lower(btrim(location_name)));

