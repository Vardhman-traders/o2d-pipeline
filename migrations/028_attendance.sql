-- One row per employee per day. Times are Indian time. final_status 'Incomplete' = checked in, not checked out yet (the 8 PM
-- auto check-out turns it into a real status).
CREATE TABLE fact_attendance (
    attendance_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_key    integer NOT NULL REFERENCES dim_att_employee (employee_key),
    work_date       date NOT NULL,
    check_in_time   time NOT NULL,
    location_key    integer REFERENCES dim_att_location (location_key),
    distance_m      integer,
    photo_in_key    bigint REFERENCES file_attachment (attachment_key) ON DELETE SET NULL,
    check_out_time  time,
    checkout_source varchar(20) CHECK (checkout_source IN ('Self', 'Manual (Owner)', 'Auto (8 PM)', 'Auto (Fix)')),
    photo_out_key   bigint REFERENCES file_attachment (attachment_key) ON DELETE SET NULL,
    hours_worked_min integer,
    final_status    varchar(12) NOT NULL DEFAULT 'Incomplete'
                    CHECK (final_status IN ('Present', 'Late', 'Half Day', 'Absent', 'Incomplete')),
    wa_status       varchar(20) CHECK (wa_status IN ('IN Pending', 'IN Sent', 'OUT Pending', 'IN+OUT Pending', 'Done', 'Done (Auto)', 'Skipped (No WA)')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz,
    UNIQUE (employee_key, work_date)
);
CREATE INDEX idx_attendance_date ON fact_attendance (work_date);
CREATE INDEX idx_attendance_wa ON fact_attendance (wa_status) WHERE wa_status LIKE '%Pending';

CREATE TABLE fact_att_advance (
    advance_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_key integer NOT NULL REFERENCES dim_att_employee (employee_key),
    advance_date date NOT NULL DEFAULT CURRENT_DATE,
    amount       numeric(12, 2) NOT NULL CHECK (amount > 0),
    note         text,
    added_by_user_key integer REFERENCES dim_user (user_key) ON DELETE SET NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_att_advance_emp ON fact_att_advance (employee_key, advance_date);

-- Every WhatsApp attempt (what the old script kept in its WA_Log sheet); the oldest are trimmed by the nightly run.
CREATE TABLE att_wa_log (
    log_key       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sent_at       timestamptz NOT NULL DEFAULT now(),
    kind          varchar(20) NOT NULL,
    employee_name varchar(100),
    http_code     integer,
    ok            boolean NOT NULL,
    response      text
);

-- The 8 PM auto check-out is done once a day (and only by one copy of the service).
CREATE TABLE att_auto_run (
    run_date    date PRIMARY KEY,
    closed      integer NOT NULL DEFAULT 0,
    ran_at      timestamptz NOT NULL DEFAULT now()
);

-- A location added in Setup without an order goes to the end of the list.
CREATE FUNCTION att_default_sort() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.sort_order = 0 THEN
        SELECT COALESCE(max(sort_order), 0) + 1 INTO NEW.sort_order FROM dim_att_location;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_att_location_sort BEFORE INSERT ON dim_att_location FOR EACH ROW EXECUTE FUNCTION att_default_sort();
