-- 033: Cashier dashboard -> Payments ("Sales" / "Sales Return" tabs, awaiting merge).
--   dim_payment_status.payments_split - Setup > Dropdown values > Payment status > "Cash / bank split": how the money of an order with
--       this status is split when it reaches Payments (all cash, all bank, or the cashier splits it: Cash + Bank).
--   payment_push - one row per order the cashier confirmed: the order's money waiting to be completed (company, party, ...) and merged
--       into Payments. After the merge it keeps the link to the Payments entries (a Cash and / or a Bank entry) and what was merged,
--       so an order that is edited afterwards comes back as "already merged" and updates those entries instead of adding new ones.
--   fact_payment_txn.order_warning - set when the order behind an entry changed after it was merged (the entry itself is not touched).
--   Sales and Sale Return are no longer typed by hand on the Payments page: they arrive from the Cashier dashboard.

ALTER TABLE dim_payment_status ADD COLUMN payments_split varchar(4) CHECK (payments_split IN ('cash', 'bank', 'both'));

UPDATE dim_payment_status SET payments_split = 'cash' WHERE lower(btrim(status_name)) = 'cash';
UPDATE dim_payment_status SET payments_split = 'bank' WHERE lower(btrim(status_name)) = 'bank';
UPDATE dim_payment_status SET payments_split = 'both'
WHERE lower(regexp_replace(btrim(status_name), '\s+', ' ', 'g')) IN ('cash + bank', 'cash+bank', 'cash and bank', 'cash & bank');

ALTER TABLE fact_payment_txn ADD COLUMN order_warning varchar(200);

CREATE TABLE payment_push (
    push_key           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_key          integer NOT NULL UNIQUE REFERENCES fact_orders (order_key) ON DELETE CASCADE,
    kind               varchar(6) NOT NULL CHECK (kind IN ('sales', 'return')),
    status             varchar(8) NOT NULL DEFAULT 'awaiting' CHECK (status IN ('awaiting', 'merged')),
    txn_date           date,
    company_key        integer REFERENCES dim_company (company_key),
    party_name         varchar(150),
    cash_amount        numeric(14, 2) NOT NULL DEFAULT 0 CHECK (cash_amount >= 0),
    bank_amount        numeric(14, 2) NOT NULL DEFAULT 0 CHECK (bank_amount >= 0),
    remarks            text,
    order_amount       numeric(14, 2),              -- what the order shows (entered / 100): cash + bank must add up to it
    pushed_by_user_key integer REFERENCES dim_user (user_key),
    pushed_at          timestamptz NOT NULL DEFAULT now(),
    merged_by_user_key integer REFERENCES dim_user (user_key),
    merged_at          timestamptz,
    cash_txn_key       bigint REFERENCES fact_payment_txn (txn_key) ON DELETE SET NULL,
    bank_txn_key       bigint REFERENCES fact_payment_txn (txn_key) ON DELETE SET NULL,
    merged_kind        varchar(6),                   -- what was merged last (to show old -> new when the order changes)
    merged_cash        numeric(14, 2),
    merged_bank        numeric(14, 2),
    edited_after_merge boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_payment_push_status ON payment_push (status);

-- A confirmation is only true for the money it confirmed. Now also reacts to the things that decide the sign and the type of the money
-- (cancelled / delivery status / submission type), and tells Payments when the order behind a merged entry changed.
CREATE OR REPLACE FUNCTION cashier_confirmation_reset() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.payment_status_key IS DISTINCT FROM OLD.payment_status_key OR NEW.amount_received IS DISTINCT FROM OLD.amount_received
        OR NEW.delivery_status_key IS DISTINCT FROM OLD.delivery_status_key
        OR NEW.submission_type_key IS DISTINCT FROM OLD.submission_type_key
        OR NEW.is_cancelled IS DISTINCT FROM OLD.is_cancelled)
       AND NEW.cashier_confirmed_at IS NOT DISTINCT FROM OLD.cashier_confirmed_at
       AND OLD.cashier_confirmed_at IS NOT NULL THEN
        NEW.cashier_confirmed_at := NULL;
        NEW.cashier_confirmed_by_user_key := NULL;
        NEW.cashier_note := NULL;
        -- never merged: the row waiting in Payments is stale, the cashier confirms the new money and it comes back
        DELETE FROM payment_push WHERE order_key = NEW.order_key AND merged_at IS NULL;
        -- already merged: it stays linked; mark the order as changed and warn on the Payments entries
        UPDATE payment_push SET status = 'merged', edited_after_merge = true WHERE order_key = NEW.order_key AND merged_at IS NOT NULL;
        UPDATE fact_payment_txn SET order_warning = 'Order changed in O2D after this entry was merged - please review'
        WHERE txn_key IN (SELECT cash_txn_key FROM payment_push WHERE order_key = NEW.order_key AND cash_txn_key IS NOT NULL
                          UNION SELECT bank_txn_key FROM payment_push WHERE order_key = NEW.order_key AND bank_txn_key IS NOT NULL);
    END IF;
    RETURN NEW;
END
$$;

