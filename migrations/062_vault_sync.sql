-- 062: bookkeeping for the encrypted export (app/vault_export.py). Nothing here holds business data.
--   vault_batch      one row per export: full (everything) or delta (only what changed since the last CONFIRMED batch)
--   vault_row_state  a keyed fingerprint of every exported row as of each batch, so the next export can tell what changed.
--                    The fingerprint is an HMAC with a secret that is not in the database, so it reveals nothing about a row.

CREATE TABLE vault_batch (
    batch_no     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         varchar(10) NOT NULL CHECK (kind IN ('full', 'delta')),
    base_batch   integer NOT NULL DEFAULT 0,
    status       varchar(12) NOT NULL DEFAULT 'building'
    CHECK (status IN ('building', 'pending', 'confirmed', 'failed', 'superseded')),
    export_id    varchar(32),
    created_at   timestamptz NOT NULL DEFAULT now(),
    confirmed_at timestamptz,
    summary      jsonb
);

CREATE TABLE vault_row_state (
    batch_no   integer NOT NULL REFERENCES vault_batch (batch_no) ON DELETE CASCADE,
    table_name varchar(64) NOT NULL,
    row_key    text NOT NULL,
    fp         bytea NOT NULL,
    PRIMARY KEY (batch_no, table_name, row_key)
);
