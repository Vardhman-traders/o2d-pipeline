-- A value added from Setup without an order number goes to the end of its list (stage order is the order they are offered in).
CREATE FUNCTION decor_default_sort() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.sort_order = 0 THEN
        IF TG_TABLE_NAME = 'dim_decor_stage' THEN
            SELECT COALESCE(max(sort_order), 0) + 1 INTO NEW.sort_order FROM dim_decor_stage WHERE product_type_key = NEW.product_type_key;
        ELSIF TG_TABLE_NAME = 'dim_decor_product_type' THEN
            SELECT COALESCE(max(sort_order), 0) + 1 INTO NEW.sort_order FROM dim_decor_product_type;
        ELSE
            SELECT COALESCE(max(sort_order), 0) + 1 INTO NEW.sort_order FROM dim_decor_expense_type;
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_decor_stage_sort BEFORE INSERT ON dim_decor_stage FOR EACH ROW EXECUTE FUNCTION decor_default_sort();
CREATE TRIGGER trg_decor_type_sort BEFORE INSERT ON dim_decor_product_type FOR EACH ROW EXECUTE FUNCTION decor_default_sort();
CREATE TRIGGER trg_decor_exptype_sort BEFORE INSERT ON dim_decor_expense_type FOR EACH ROW EXECUTE FUNCTION decor_default_sort();
