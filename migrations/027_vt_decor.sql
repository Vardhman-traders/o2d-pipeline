-- ------------------------------------------------------------------ clients and their logs
CREATE TABLE dim_decor_client (
    client_key       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_code      text GENERATED ALWAYS AS ('C' || lpad(client_key::text, 3, '0')) STORED,
    client_name      varchar(150) NOT NULL,
    mobile           varchar(30) NOT NULL,
    address          text,
    product          text,
    contract_amount  numeric(14, 2) NOT NULL DEFAULT 0,
    start_date       date NOT NULL DEFAULT CURRENT_DATE,
    notes            text,
    status           varchar(10) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Completed', 'Hidden')),
    assigned_to      varchar(60),          -- the staff member's sign-in name (lower case); blank = owner's own
    added_by         varchar(60),
    product_type_key integer NOT NULL REFERENCES dim_decor_product_type (type_key),
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_decor_client_code ON dim_decor_client (client_code);
CREATE INDEX idx_decor_client_status ON dim_decor_client (status);

CREATE TABLE fact_decor_payment (
    payment_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_key   integer NOT NULL REFERENCES dim_decor_client (client_key) ON DELETE CASCADE,
    stage_key    integer REFERENCES dim_decor_stage (stage_key),
    stage_text   varchar(80),             -- only for an old payment whose stage is no longer in the list
    amount       numeric(14, 2) NOT NULL CHECK (amount <> 0),
    mode_key     integer REFERENCES dim_payment_mode (mode_key),
    pay_date     date NOT NULL DEFAULT CURRENT_DATE,
    ref_no       varchar(80),
    remarks      text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    created_by_user_key integer REFERENCES dim_user (user_key)
);
CREATE INDEX idx_decor_payment_client ON fact_decor_payment (client_key);
CREATE INDEX idx_decor_payment_date ON fact_decor_payment (pay_date);

CREATE TABLE fact_decor_expense (
    expense_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_key   integer NOT NULL REFERENCES dim_decor_client (client_key) ON DELETE CASCADE,
    expense_type varchar(100) NOT NULL,
    amount       numeric(14, 2) NOT NULL CHECK (amount <> 0),
    exp_date     date NOT NULL DEFAULT CURRENT_DATE,
