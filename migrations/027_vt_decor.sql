-- Money is stored as actual rupees (the screen divides what is typed by 100, as the old VT Decor page did).

-- ------------------------------------------------------------------ Setup lists
CREATE TABLE dim_decor_product_type (
    type_key       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name      varchar(50) NOT NULL,
    percent_stages boolean NOT NULL DEFAULT false,   -- true: each stage has a share of the contract (Wallpaper 40/30/20/10)
    sort_order     integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_decor_product_type ON dim_decor_product_type (lower(btrim(type_name)));

CREATE TABLE dim_decor_stage (
    stage_key       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_type_key integer NOT NULL REFERENCES dim_decor_product_type (type_key),
    stage_name      varchar(80) NOT NULL,
    target_pct      integer NOT NULL DEFAULT 0 CHECK (target_pct BETWEEN 0 AND 100),
    sort_order      integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_decor_stage ON dim_decor_stage (product_type_key, lower(btrim(stage_name)));

-- Suggestions offered when an expense is typed (the field stays free text, as before).
CREATE TABLE dim_decor_expense_type (
    expense_type_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_type_name varchar(100) NOT NULL,
    sort_order       integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_decor_expense_type ON dim_decor_expense_type (lower(btrim(expense_type_name)));

