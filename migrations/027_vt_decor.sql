    created_at   timestamptz NOT NULL DEFAULT now(),
    created_by_user_key integer REFERENCES dim_user (user_key)
);
CREATE INDEX idx_decor_expense_client ON fact_decor_expense (client_key);

CREATE TABLE fact_decor_item (
    item_key   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_key integer NOT NULL REFERENCES dim_decor_client (client_key) ON DELETE CASCADE,
    item_index integer NOT NULL,          -- 1, 2, 3 ... within the client
    product    text NOT NULL,
    amount     numeric(14, 2) NOT NULL DEFAULT 0,
    item_date  date NOT NULL DEFAULT CURRENT_DATE,
    notes      text,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_key integer REFERENCES dim_user (user_key)
);
CREATE INDEX idx_decor_item_client ON fact_decor_item (client_key);

CREATE TABLE fact_decor_revision (
    revision_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_key   integer NOT NULL REFERENCES dim_decor_client (client_key) ON DELETE CASCADE,
    old_amount   numeric(14, 2) NOT NULL,
    new_amount   numeric(14, 2) NOT NULL,
    reason       text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    created_by_user_key integer REFERENCES dim_user (user_key)
);

-- Site photos and expense challans. The file is a file_attachment (module 'decor'); legacy_url keeps a link carried over
