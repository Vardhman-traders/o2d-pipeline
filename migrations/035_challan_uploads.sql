-- 035: "Upload Challan" in the Payments module - a simple register of challan photos (or PDFs): the picture, the challan date, an
-- optional challan number / note, and who uploaded it and when.
--
-- Reused, not recreated:   file_attachment (the file itself, in R2, module = 'challan'), dim_date (the challan date),
--                          dim_user (who uploaded), page_access / user_page_access (Setup > Access: page pay_challan).
-- New:                     fact_challan_upload (one row per upload).

CREATE TABLE fact_challan_upload (
    challan_key         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challan_date_key    integer NOT NULL REFERENCES dim_date (date_key),
    reference           varchar(100),                                   -- the challan number, if the uploader types one
    note                varchar(500),
    attachment_key      bigint NOT NULL REFERENCES file_attachment (attachment_key),
    uploaded_by_user_key integer REFERENCES dim_user (user_key),
    uploaded_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_challan_upload_date ON fact_challan_upload (challan_date_key);
CREATE INDEX idx_challan_upload_by ON fact_challan_upload (uploaded_by_user_key);
