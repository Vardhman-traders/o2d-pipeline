-- 061: attendance punches are checked for buddy punching (one person marking for another). Nothing here blocks a punch; doubtful ones are
-- flagged and the admins are told, and the owner marks each one OK or "not the same person".
--   att_employee_face   the clear reference photos the admin adds for an employee (the fingerprint of the face, and the stored picture)
--   att_punch_check     one row per check-in / check-out: which phone made it (a random id kept in the phone, stored hashed), the address, a
--                       fingerprint of the photo, how the face compared (score; match / mismatch / no_face / not_enrolled / unavailable),
--                       what was flagged, and the owner's verdict

CREATE TABLE att_employee_face (
    face_key            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_key        integer NOT NULL REFERENCES dim_att_employee (employee_key) ON DELETE CASCADE,
    attachment_key      bigint REFERENCES file_attachment (attachment_key) ON DELETE SET NULL,
    embedding           real[] NOT NULL,
    created_by_user_key integer REFERENCES dim_user (user_key) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_att_employee_face_emp ON att_employee_face (employee_key);

CREATE TABLE att_punch_check (
    attendance_key       bigint NOT NULL REFERENCES fact_attendance (attendance_key) ON DELETE CASCADE,
    kind                 varchar(3) NOT NULL CHECK (kind IN ('in', 'out')),
    device_hash          char(64),
    client_ip            varchar(64),
    photo_sha256         char(64),
    face_status          varchar(12) NOT NULL DEFAULT 'unavailable'
                         CHECK (face_status IN ('match', 'mismatch', 'no_face', 'not_enrolled', 'unavailable')),
    face_score           real,
    flags                text NOT NULL DEFAULT '',
    review_result        varchar(8) CHECK (review_result IN ('ok', 'not_same')),
    reviewed_by_user_key integer REFERENCES dim_user (user_key) ON DELETE SET NULL,
    reviewed_at          timestamptz,
    review_note          text,
    created_at           timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (attendance_key, kind)
);
CREATE INDEX idx_att_punch_check_device ON att_punch_check (device_hash) WHERE device_hash IS NOT NULL;
CREATE INDEX idx_att_punch_check_photo ON att_punch_check (photo_sha256) WHERE photo_sha256 IS NOT NULL;
CREATE INDEX idx_att_punch_check_flagged ON att_punch_check (created_at DESC) WHERE flags <> '' AND review_result IS NULL;
