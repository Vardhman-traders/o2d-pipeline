-- The checklist itself: what, how often, who. One assignee per checklist (a list for two people is two checklists).
--   Daily     every day except the weekly off day (Setup > Module settings)
--   Weekly    every week on due_dow            (0 = Sunday ... 6 = Saturday, like the weekly off setting)
--   Monthly   every month on due_day           (31 = the last day of the month)
--   Quarterly every three months on due_day, starting from due_month
--   Yearly    once a year on due_month / due_day
--   Once      only on start_date
CREATE TABLE dim_checklist (
    checklist_key    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            varchar(200) NOT NULL,
    description      text,
    category_key     integer REFERENCES dim_checklist_category (category_key),
    assignee_user_key integer NOT NULL REFERENCES dim_user (user_key),
    frequency        varchar(10) NOT NULL CHECK (frequency IN ('Daily', 'Weekly', 'Monthly', 'Quarterly', 'Yearly', 'Once')),
    due_dow          smallint CHECK (due_dow BETWEEN 0 AND 6),
    due_day          smallint CHECK (due_day BETWEEN 1 AND 31),
    due_month        smallint CHECK (due_month BETWEEN 1 AND 12),
    start_date_key   integer NOT NULL REFERENCES dim_date (date_key),
    end_date_key     integer REFERENCES dim_date (date_key),
    is_active        boolean NOT NULL DEFAULT true,
    created_by_user_key integer REFERENCES dim_user (user_key),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz,
    import_batch_id  integer REFERENCES import_batch (batch_id),
    CHECK ((frequency <> 'Weekly' OR due_dow IS NOT NULL)
       AND (frequency NOT IN ('Monthly', 'Quarterly', 'Yearly') OR due_day IS NOT NULL)
       AND (frequency NOT IN ('Quarterly', 'Yearly') OR due_month IS NOT NULL))
);
CREATE INDEX idx_checklist_assignee ON dim_checklist (assignee_user_key) WHERE is_active;
CREATE INDEX idx_checklist_import_batch ON dim_checklist (import_batch_id) WHERE import_batch_id IS NOT NULL;
CREATE INDEX idx_checklist_category ON dim_checklist (category_key);

-- One row per checklist per due date, created as the calendar is looked at (never twice: the unique key).
-- assignee_user_key is copied here so re-assigning a checklist later does not rewrite who was responsible in the past.
CREATE TABLE fact_checklist_occurrence (
    occurrence_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_key   integer NOT NULL REFERENCES dim_checklist (checklist_key) ON DELETE CASCADE,
    due_date_key    integer NOT NULL REFERENCES dim_date (date_key),
    assignee_user_key integer NOT NULL REFERENCES dim_user (user_key),
    status          varchar(10) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Done', 'Not Done')),
    marked_at       timestamptz,
    marked_by_user_key integer REFERENCES dim_user (user_key),
    remark          text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (checklist_key, due_date_key),
    CHECK (status = 'Pending' OR marked_at IS NOT NULL)
);
CREATE INDEX idx_checklist_occ_due ON fact_checklist_occurrence (due_date_key);
CREATE INDEX idx_checklist_occ_assignee ON fact_checklist_occurrence (assignee_user_key, due_date_key);

