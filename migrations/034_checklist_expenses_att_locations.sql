-- 034: three additions on the existing star schema.
--
--   1. Attendance - which work places an employee may mark attendance from (no row = any work place, as before).
--   2. Checklist  - recurring compliance / routine checklists inside the Delegation module: a calendar, a creation form and a
--                   "mark done / not done" list for the person it is assigned to.
--   3. Regular expenses - a running float (opening balance + top-ups - expenses) in the Payments module.
--
-- Reused, not recreated:   dim_user (assignee, who marked it, who spent), dim_date (every due / expense date), app_config (the weekly
--                          off day the Daily checklists skip), import_batch (bulk upload + undo), admin_audit_log,
--                          page_access / user_page_access (Setup > Access switches each page on or off), dim_att_location.
-- New:                     att_employee_location; dim_checklist_category, dim_checklist, fact_checklist_occurrence;
--                          dim_expense_account, dim_expense_category, fact_expense_entry.

-- ------------------------------------------------------------------ 1. attendance: allowed work places per employee
CREATE TABLE att_employee_location (
    employee_key integer NOT NULL REFERENCES dim_att_employee (employee_key) ON DELETE CASCADE,
    location_key integer NOT NULL REFERENCES dim_att_location (location_key) ON DELETE CASCADE,
    PRIMARY KEY (employee_key, location_key)
);
CREATE INDEX idx_att_employee_location_loc ON att_employee_location (location_key);

