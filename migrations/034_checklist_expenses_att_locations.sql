-- One row per top-up or expense. A wrong entry is voided (kept, with who and why), never edited or deleted, so the balance can
-- always be explained. The balance of an account = opening + top-ups - expenses, counting only entries that are not voided.
CREATE TABLE fact_expense_entry (
    entry_key       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_no        text GENERATED ALWAYS AS ('EXP-' || lpad(entry_key::text, 5, '0')) STORED,
    account_key     integer NOT NULL REFERENCES dim_expense_account (account_key),
    entry_date_key  integer NOT NULL REFERENCES dim_date (date_key),
    kind            varchar(8) NOT NULL CHECK (kind IN ('Topup', 'Expense')),
    amount          numeric(14, 2) NOT NULL CHECK (amount > 0),
    category_key    integer REFERENCES dim_expense_category (category_key),
    spent_by_user_key integer REFERENCES dim_user (user_key),     -- who spent it / who handed the money in
    paid_to         varchar(150),                                 -- the shop, driver, vendor ... (free text)
    description     text,
    created_by_user_key integer REFERENCES dim_user (user_key),
    created_at      timestamptz NOT NULL DEFAULT now(),
    voided_at       timestamptz,
    voided_by_user_key integer REFERENCES dim_user (user_key),
    void_reason     text,
    CHECK (kind = 'Topup' OR category_key IS NOT NULL),
    CHECK ((voided_at IS NULL) = (void_reason IS NULL))
);
CREATE INDEX idx_expense_entry_account_date ON fact_expense_entry (account_key, entry_date_key);
CREATE INDEX idx_expense_entry_category ON fact_expense_entry (category_key);
