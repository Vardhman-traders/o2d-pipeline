-- ------------------------------------------------------------------ 3. regular expenses
-- An account is one float of money: "Petty cash - Shop". It starts with an opening balance; top-ups add to it, expenses take away.
CREATE TABLE dim_expense_account (
    account_key     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_name    varchar(80) NOT NULL,
    opening_balance numeric(14, 2) NOT NULL DEFAULT 0 CHECK (opening_balance >= 0),
    sort_order      integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_expense_account_name ON dim_expense_account (lower(btrim(account_name)));

CREATE TABLE dim_expense_category (
